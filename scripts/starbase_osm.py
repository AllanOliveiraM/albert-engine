#!/usr/bin/env python3
"""Starbase's launch site from OpenStreetMap (ODbL, (c) OpenStreetMap contributors) as scenery parts and road centre lines for
examples/starbase_osm.hpp: storage tanks, buildings, the other tower, roads, in metres east/north of the pad's site.
Usage: starbase_osm.py OVERPASS_JSON LAT LON > examples/starbase_osm.hpp"""
import json,math,sys
data=json.load(open(sys.argv[1]));lat0,lon0=float(sys.argv[2]),float(sys.argv[3])
a=6378137.0;e2=6.69437999014e-3;ph=math.radians(lat0)
mlat=a*(1-e2)/(1-e2*math.sin(ph)**2)**1.5*math.pi/180;mlon=a/math.sqrt(1-e2*math.sin(ph)**2)*math.cos(ph)*math.pi/180
def enu(g):return ((g['lon']-lon0)*mlon,(g['lat']-lat0)*mlat)
def box(pts): # Centre, length along the long axis, width across, heading of the long axis (degrees from north), by PCA.
    if pts[0]==pts[-1]:pts=pts[:-1]
    cx=sum(p[0] for p in pts)/len(pts);cy=sum(p[1] for p in pts)/len(pts)
    sxx=sum((p[0]-cx)**2 for p in pts);syy=sum((p[1]-cy)**2 for p in pts);sxy=sum((p[0]-cx)*(p[1]-cy) for p in pts)
    t=0.5*math.atan2(2*sxy,sxx-syy);ux,uy=math.cos(t),math.sin(t)
    al=[(p[0]-cx)*ux+(p[1]-cy)*uy for p in pts];ac=[-(p[0]-cx)*uy+(p[1]-cy)*ux for p in pts]
    l,w=max(al)-min(al),max(ac)-min(ac);mx=(max(al)+min(al))/2;my=(max(ac)+min(ac))/2
    return cx+mx*ux-my*uy,cy+mx*uy+my*ux,l,w,math.degrees(math.atan2(ux,uy))%180
def height(t,default):
    try:return float(t.get('height','').split()[0])
    except (ValueError,IndexError):return default
rows=[]
for e in data['elements']:
    t=e.get('tags',{})
    if e['type']!='way' or 'geometry' not in e:continue
    pts=[enu(g) for g in e['geometry']]
    if len(pts)<3:continue
    x,y,l,w,hd=box(pts)
    name=t.get('name','')
    if 'Integration Tower 1' in name or 'Flame Trench' in name:continue # The pad's own (Pad 1 as rebuilt for V3): drawn by the mission.
    if t.get('man_made')=='gantry':continue # Towers' arms, the pad's mount: drawn by the mission.
    if t.get('man_made')=='tower':rows.append(('tower',x,y,l,w,hd,height(t,140),name));continue
    if t.get('man_made')=='storage_tank':
        content=t.get('content','')
        if l>2.2*w:rows.append(('lying tank',x,y,l,w,hd,w,content));continue
        d=(l+w)/2;rows.append(('tank',x,y,d,d,0,height(t,6 if d<5 else 1.6*d),content));continue
    if 'building' in t:
        if l>70 and w<25:rows.append(('trench',x,y,l,w,hd,6,name or 'Pad 2 flame trench'));continue # Untagged: Pad 2's, 84 x 18 m.
        rows.append(('building',x,y,l,w,hd,height(t,8 if l*w>400 else 4),name))
print('#pragma once\n// Generated by scripts/starbase_osm.py from OpenStreetMap (ODbL, (c) OpenStreetMap contributors): Starbase\'s launch site\n'
      '// around the pad, in metres east and north of its site: kind, centre, length (along heading), width, heading (deg), height.\n'
      'namespace albert::example::starship {\nstruct OsmPart {const char* kind;double x,y,length,width,heading,height;const char* name;};\ninline constexpr OsmPart starbaseOsm[]{')
for k,x,y,l,w,hd,h,n in rows:print(f'    {{"{k}",{x:.1f},{y:.1f},{l:.1f},{w:.1f},{hd:.1f},{h:.1f},"{n}"}},')
print('};\n}')
# Keep the saved centre lines and OSM ids; no simplification or imagery-dependent offsets.
roads=[]
for e in data['elements']:
    t=e.get('tags',{});h=t.get('highway')
    if e['type']!='way' or not h or 'geometry' not in e:continue
    pts=[enu(g) for g in e['geometry']]
    pts=[p for i,p in enumerate(pts) if not i or math.dist(p,pts[i-1])>.01]
    if len(pts)<2:continue
    highway=h in ('tertiary','unclassified') and t.get('lanes')=='2'
    surface=t.get('surface','concrete' if h=='service' else 'sand')
    kind={'asphalt':0,'concrete':1,'compacted':2}.get(surface,3)
    width=10.5 if highway else 6 if t.get('junction')=='roundabout' else 7 if h=='service' else 3.5 if h=='track' else 1.5
    try:width=float(t.get('width',str(width)).split()[0])
    except (ValueError,IndexError):pass
    roads.append((e['id'],pts,width,kind,highway,h=='service'))
def at_highway(p):
    for _,pts,w,_,hw,_ in roads:
        if not hw:continue
        for a,b in zip(pts,pts[1:]):
            dx,dy=b[0]-a[0],b[1]-a[1];q=max(0,min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy)))
            if math.hypot(p[0]-a[0]-q*dx,p[1]-a[1]-q*dy)<w/2+1:return True
    return False
print('namespace albert::example::starship {\nstruct OsmRoadPoint {double x,y;};\ninline constexpr OsmRoadPoint starbaseRoadPoints[]{')
for _,pts,_,_,_,_ in roads:
    for x,y in pts:print(f'    {{{x:.3f},{y:.3f}}},')
print('};\nstruct OsmRoad {unsigned long long id;unsigned first,count;double width;int surface;bool highway,stopStart,stopEnd;};\ninline constexpr OsmRoad starbaseRoads[]{')
first=0
for ident,pts,w,kind,hw,service in roads:
    boolean=lambda b:'true' if b else 'false'
    print(f'    {{{ident},{first},{len(pts)},{w:g},{kind},{boolean(hw)},{boolean(service and at_highway(pts[0]))},{boolean(service and at_highway(pts[-1]))}}},')
    first+=len(pts)
print('};\n}')
