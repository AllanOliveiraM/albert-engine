#!/usr/bin/env python3
"""Seal a small, offline catalogue. Network is used only by this authoring tool.

Osculating elements are propagated as two-body ellipses, not as live ephemerides.
Raw Horizons replies and reference vectors are retained for provenance/testing.
"""
import argparse, hashlib, json, math, pathlib, re, time, urllib.parse, urllib.request
ROOT=pathlib.Path(__file__).resolve().parents[1]
MOONS=['phobos','deimos','io','europa','ganymede','callisto','mimas','enceladus','tethys','dione','rhea','titan','hyperion','iapetus','phoebe','ariel','umbriel','titania','oberon','miranda','triton','nereid','proteus','charon']
EXTRA=[('pluto','Plutao','999',1188300,'Dwarf'),('ceres','Ceres','1;',469700,'Dwarf'),('eris','Eris','136199;',1163000,'Dwarf'),('haumea','Haumea','136108;',780000,'Dwarf'),('makemake','Makemake','136472;',715000,'Dwarf'),('vesta','Vesta','4;',262700,'Asteroid'),('pallas','Pallas','2;',256000,'Asteroid'),('halley','Halley','DES=1P;CAP',5500,'Comet'),('67p','67P / Churyumov-Gerasimenko','DES=67P;CAP',1650,'Comet')]
def write_changed(path,text):
 if path.exists() and path.read_text()==text:return
 temporary=path.with_suffix(path.suffix+'.tmp');temporary.write_text(text);temporary.replace(path)
def main():
 parser=argparse.ArgumentParser();parser.add_argument('--offline',action='store_true');args=parser.parse_args()
 cache=ROOT/'asset-packs/catalog';cache.mkdir(parents=True,exist_ok=True)
 epoch=2461329.5 # 2026-10-16 00:00 TDB, explicitly not a runtime timestamp.
 bodies=[]
 for match in re.finditer(r'\{"([^"]+)","([^"]+)",(\d+),([\d.]+),', (ROOT/'src/catalog/moons.inc').read_text()):
  id,name,code,radius=match.groups()
  if id in MOONS:
   parent={'4':'mars','5':'jupiter','6':'saturn','7':'uranus','8':'neptune','9':'pluto'}[code[0]]
   bodies.append((id,name,code,float(radius),'Moon',parent,str(int(code)//100*100+99)))
 bodies=[(*v,'sun','10') for v in EXTRA]+bodies
 rows=[];sources=[]
 def request(code,center,kind,id):
  params=dict(format='json',COMMAND="'"+code+"'",CENTER="'500@"+center+"'",MAKE_EPHEM="'YES'",EPHEM_TYPE="'"+kind+"'",TLIST="'"+str(epoch)+"'",REF_PLANE="'FRAME'",REF_SYSTEM="'ICRF'",OUT_UNITS="'KM-S'",CSV_FORMAT="'YES'",VEC_TABLE="'2'",VEC_CORR="'NONE'")
  url='https://ssd.jpl.nasa.gov/api/horizons.api?'+urllib.parse.urlencode(params)
  path=cache/(id+'-'+kind.lower()+'.json')
  if not path.exists():
   if args.offline:raise RuntimeError('Missing source '+str(path))
   for attempt in range(4):
    try:
     with urllib.request.urlopen(url,timeout=50) as reply:data=reply.read(2*1024*1024)
     doc=json.loads(data)
     if '$$SOE' not in doc.get('result',''):raise RuntimeError(doc.get('error',doc.get('result',''))[:500])
     path.write_bytes(data);break
    except Exception:
     if attempt==3:raise
     time.sleep(2*(attempt+1))
   time.sleep(.2) # SSD API: sequential requests only.
  result=json.loads(path.read_text())['result'];values=result.split('$$SOE')[1].split('$$EOE')[0].strip().split(',')
  return [float(v) for v in values[2:] if v.strip()],url
 for id,name,code,radius,category,parent,center in bodies:
  v,url=request(code,center,'ELEMENTS',id)
  # CSV: EC, QR, IN, OM, W, Tp, N, MA, TA, A, AD, PR.
  e,q,inc,node,peri,tp,n,ma,ta,a,ad,period=v
  if not all(math.isfinite(x) for x in v) or not 0<=e<1 or not a>0 or not period>0:raise ValueError('Only bound ellipses are supported')
  ref,_=request(code,center,'VECTORS',id)
  rows.append(dict(id=id,name=name,parent=parent,category=category,radius_m=radius,epoch_jd_tdb=epoch,a_m=a*1000,e=e,inclination_deg=inc,node_deg=node,periapsis_deg=peri,mean_anomaly_deg=ma,mean_motion_deg_s=n,period_s=period,reference_position_m=[x*1000 for x in ref[:3]],reference_velocity_m_s=[x*1000 for x in ref[3:6]]))
  sources.append(dict(id=id,url=url,elements_sha256=hashlib.sha256((cache/(id+'-elements.json')).read_bytes()).hexdigest(),vectors_sha256=hashlib.sha256((cache/(id+'-vectors.json')).read_bytes()).hexdigest()));print('Local catalogue:',id,flush=True)
 doc=dict(format='albert-local-elements-v1',source='NASA/JPL Horizons',frame='ICRF',units='SI',limits='Two-body approximation from osculating elements at the stated epoch. Perturbations, precession and non-gravitational effects are not integrated. Simplified spheres, no photographic surface claim.',sources=sources,bodies=rows)
 out=ROOT/'assets/catalog';out.mkdir(parents=True,exist_ok=True);write_changed(out/'orbits.json',json.dumps(doc,indent=2)+'\n')
 lines=['// Generated by scripts/prepare-local-catalog.py; source and limits: assets/catalog/orbits.json.']
 for v in rows:
  values=[v[k] for k in ['radius_m','epoch_jd_tdb','a_m','e','inclination_deg','node_deg','periapsis_deg','mean_anomaly_deg','mean_motion_deg_s','period_s']]
  lines.append('{'+','.join([json.dumps(v[k]) for k in ['id','name','parent']]+['Category::'+v['category']]+[format(x,'.17g') for x in values])+ '},')
 write_changed(ROOT/'src/core/local_orbits.inc','\n'.join(lines)+'\n')
 fixtures=[]
 for v in rows:fixtures.append('{'+json.dumps(v['id'])+',{'+','.join(format(x,'.17g') for x in v['reference_position_m'])+'},{'+','.join(format(x,'.17g') for x in v['reference_velocity_m_s'])+'}},')
 write_changed(ROOT/'tests/local_orbits_fixture.inc','\n'.join(fixtures)+'\n')
 record_path=out/'orbits.json';payload=record_path.read_bytes();manifest_path=ROOT/'assets/manifest.json';manifest=json.loads(manifest_path.read_text())
 record=dict(path='catalog/orbits.json',bytes=len(payload),sha256=hashlib.sha256(payload).hexdigest(),source='Generated by scripts/prepare-local-catalog.py; NASA/JPL query URLs are in this file',license='Public astronomical data; provenance and limits in docs/LOCAL_SYSTEM.md',processing='ICRF/SI osculating elements and independent reference vectors at the stated TDB epoch')
 manifest['files']=[entry for entry in manifest['files'] if entry['path']!=record['path']]+[record]
 write_changed(manifest_path,json.dumps(manifest,indent=2)+'\n')
if __name__=='__main__':main()
